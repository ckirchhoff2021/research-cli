_STYLE_MAP = {s["id"]: s for s in ART_STYLES}


def get_style(art_style: str | None) -> dict:
    """按 id 取画风；未知/缺省回退默认 3D 卡通。"""
    return _STYLE_MAP.get(art_style or "", _STYLE_MAP[DEFAULT_ART_STYLE])


def style_anchor(art_style: str | None) -> str:
    """返回带'非真人'总约束的完整 anchor（用于视频 prompt 前置）。"""
    return f"{get_style(art_style)['anchor']}，{_NON_REAL}"


def style_choices() -> list[dict]:
    """供前端选择的精简目录（不含长 prompt 文本）。"""
    return [{"id": s["id"], "label": s["label"], "icon": s["icon"], "desc": s["desc"]}
            for s in ART_STYLES]


# 与"非真人"要求冲突的措辞 → 替换为动画/插画语境（顺序敏感：长词在前）
_REAL_WORDS: list[tuple[str, str]] = [
    ("细腻细腻动画颗粒", "细腻动画颗粒"),
    ("轻微细腻动画颗粒", "轻微动画颗粒"),
    ("真人照片质感", "动画渲染质感"),
    ("真实摄影人像", "动画人物形象"),
    ("真实人像", "动画人物形象"),
    ("胶片颗粒", "动画颗粒"),
    ("胶片感", "动画电影感"),
    ("胶片", "动画电影"),
    ("写实质感", "风格化质感"),
    ("写实风格", "风格化风格"),
    ("写实", "风格化"),
    ("实拍", "动画画面"),
    ("真人", "动画人物"),
    ("照片感", "插画感"),
]


def sanitize_nonreal(text: str | None) -> str:
    """清除文本里暗示真人/照片/胶片的措辞，替换为动画语境。"""
    out = text or ""
    for bad, good in _REAL_WORDS:
        out = out.replace(bad, good)
    return out
